"""Writes site/data.js: the numbers the website needs, taken from the same files and model as everything else.

How this works: the page cannot run Python, so this script runs the model once, packs the
result into a small JavaScript file, and the page reads it. If the model or the inputs change,
run this again (python3 resco/export_site_data.py) and the site follows.
"""
import calendar
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model  # noqa: E402

pv = model.read_pv_month_hour()            # kWh per hour in an average day, plant of 307.4 kWp
load = model.read_load()

# average load by month and hour, split into Monday-Saturday and Sunday
sums = {}
import csv  # noqa: E402
with open(os.path.join(HERE, "..", "survey", "hourly_load.csv")) as f:
    for r in csv.DictReader(f):
        key = (int(r["month"]), int(r["hour_of_day"]), "sun" if int(r["weekday_mon0"]) == 6 else "work")
        s = sums.setdefault(key, [0.0, 0])
        s[0] += float(r["load_kw"])
        s[1] += 1

def prof(kind):
    return [[round(sums[(m, h, kind)][0] / sums[(m, h, kind)][1], 1) for h in range(24)] for m in range(1, 13)]

monthly_kwh = []
for m in range(1, 13):
    days = calendar.monthrange(2026, m)[1]
    monthly_kwh.append(round(sum(pv[m]) * days))

base = model.run()
tod = model.run(tod=True)
data = {
    "design_kwp": 307.4,
    "pv_kw_by_month_hour": [[round(x, 1) for x in pv[m]] for m in range(1, 13)],
    "load_work_kw": prof("work"),
    "load_sun_kw": prof("sun"),
    "monthly_kwh": monthly_kwh,
    "curve": sorted(model.self_consumption_curve(step=10, lo=50, hi=500) + [dict(kwp=307.4, **{k: (round(v, 1) if k != "self_fraction" else round(v, 4)) for k, v in model.year1_energy(307.4).items()})], key=lambda r: r["kwp"]),
    "inputs": model.INPUTS,
    "base_result": {k: base[k] for k in ("project_irr", "payback_years", "npv_rs", "capex_rs",
                                          "client_saving_year1_rs", "client_saving_total_rs", "resco_tariff_year1")},
    "tod_case": {k: tod[k] for k in ("project_irr", "payback_years", "client_saving_year1_rs")} | {"avoided_rate": tod["inputs"]["grid_energy_tariff"]},
    "sensitivity": model.sensitivity_table(),
}
out = os.path.join(HERE, "..", "site", "data.js")
with open(out, "w") as f:
    f.write("// Generated by resco/export_site_data.py. Do not edit by hand.\nwindow.DATA = ")
    json.dump(data, f, separators=(",", ":"))
    f.write(";\n")
print("wrote", os.path.abspath(out), os.path.getsize(out), "bytes")
