"""Writes resco/results.md from the model, so the text and the numbers cannot drift apart. Run: python3 resco/write_results.py"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model  # noqa: E402

r, t = model.run(), model.run(tod=True)
e, p = r["energy_year1"], r["inputs"]
own = e["self_kwh"] * p["grid_energy_tariff"] + e["export_kwh"] * p["feed_in_tariff"]
om = r["capex_rs"] * p["om_pct_of_capex"] / 100
rows = "\n".join(f"| {x['discount']*100:.0f}% | {x['capex']} | {x['tariff']:.2f} | {x['irr']*100:.1f}% | {x['payback']:.1f} | {x['saving1']:,.0f} |" for x in model.sensitivity_table())
text = f"""# RESCO model results (base case and sensitivity)

Generated by `python3 resco/write_results.py` from `resco/model.py`. Inputs and their sources are in the `INPUTS` table at the top of `resco/model.py`; every unsourced input is marked ASSUMED there and in `ASSUMPTIONS.md`.

*Corrected 5 Nov 2026: the first version read the WBSEDCL tariff columns the wrong way round (energy charge 3.84 Rs/kWh). The energy charge is about Rs 7.06 per kWh and 384 is the demand charge in Rs/kVA/month. All numbers below use the corrected value.*

## Base case

| Item | Value |
|---|---|
| Plant | 307.4 kWp, PVsyst year-1 output 409,153 kWh (the model rebuilds {e['pv_kwh']:,.0f} kWh from the hourly table) |
| Self-used on site | {e['self_kwh']:,.0f} kWh ({e['self_fraction']*100:.1f} %) |
| Exported | {e['export_kwh']:,.0f} kWh ({(1-e['self_fraction'])*100:.1f} %), mostly Sundays and holidays, valued at Rs 3.89 (HV feed-in) |
| Capex | Rs {p['capex_per_wp']:.0f} per Wp = Rs {r['capex_rs']/1e7:.2f} crore |
| Grid energy charge | Rs {p['grid_energy_tariff']:.2f} per kWh (WBSEDCL Rate E(B), 11 kV industry; flat, MVCA not included) |
| RESCO tariff, year 1 | 20 % below grid = Rs {r['resco_tariff_year1']:.2f} per kWh |
| O&M | 1 % of capex per year (ASSUMED) |
| Escalation | 2 % per year on both tariffs (ASSUMED) |
| Degradation | 1 % in year 1, then 0.4 % per year (Waaree warranty) |
| Contract | 25 years, no loan, no tax |

| Result | Value |
|---|---|
| RESCO project IRR | {r['project_irr']*100:.1f} % |
| RESCO simple payback | {r['payback_years']:.1f} years |
| RESCO NPV at 10 % | Rs {r['npv_rs']/1e5:.0f} lakh |
| Client saving, year 1 | Rs {r['client_saving_year1_rs']/1e5:.2f} lakh |
| Client saving over 25 years | Rs {r['client_saving_total_rs']/1e7:.2f} crore |

## Optional case: client on the time-of-day scheme, Rate E(BT)

Solar energy offsets the hour-by-hour TOD rate (06-17 h Rs 6.94, 17-23 h Rs 8.36, 23-06 h Rs 5.17, monsoon column). Because the plant runs mostly 06-17 h, the average avoided rate is Rs {t['inputs']['grid_energy_tariff']:.2f} per kWh.

| Result | Value |
|---|---|
| RESCO IRR | {t['project_irr']*100:.1f} % |
| Payback | {t['payback_years']:.1f} years |
| Client saving, year 1 | Rs {t['client_saving_year1_rs']/1e5:.2f} lakh |

## Sensitivity: RESCO IRR and client saving

| RESCO discount | Capex Rs/Wp | RESCO tariff Rs/kWh | RESCO IRR | Payback (yr) | Client saves, yr 1 (Rs) |
|---|---|---|---|---|---|
{rows}

## How to read this

- **Self-use is high ({e['self_fraction']*100:.0f} %)** because the plant is sized to the weekday daytime load. That part is robust to the tariff.
- **At about Rs 7 per kWh a 20 to 30 % discount works for both sides.** The developer earns roughly 17 to 19 % project IRR (no tax, no loan) at Rs 38 per Wp, and the client saves Rs 5 to 8 lakh in year 1 with no capex. At Rs 50 per Wp the same discounts give about 12 to 14 %.
- **Demand charge not counted.** The bill also has a demand charge of Rs 384 per kVA per month (Rate E(B) and E(BT)). Solar cannot be relied on to lower contract demand, so it is set to zero. MVCA (fuel cost adjustment, charged on top of the energy charge, value not in the document) is not counted either. Counting the demand charge would raise the client's saving; MVCA can move either way. Leaving both out keeps the base case simple and conservative.
- **RESCO versus client-owned.** If the client bought the plant it would avoid about Rs {own/1e5:.1f} lakh per year on year-1 numbers (self-use at Rs {p['grid_energy_tariff']:.2f} plus exports at Rs 3.89) against a Rs {r['capex_rs']/1e7:.2f} crore capex: about {r['capex_rs']/own:.1f} years simple payback, {r['capex_rs']/(own-om):.1f} years after O&M. A RESCO at 20 % discount trades that payback for zero upfront cost.
- **Biggest risks:** (1) capex, from two installer pages and not a quote; (2) actual yield, because soiling and shading are still zero in PVsyst; (3) the capacity-cap reading (332 kWp vs about 297 kWp, see `grid/grid_connection_note.md`); (4) the tariff, which is the FY2025-26 order escalated at an assumed 2 % for 25 years.

## Limits

1. PV output uses PVsyst's average day per month, which slightly overstates self-use compared with real cloudy days.
2. No soiling, shading or unavailability in PVsyst (see pvsyst/results.md), so output is optimistic.
3. Capex comes from two installer marketing pages, not a quote or a benchmark order.
4. No tax, depreciation benefits, loan, inverter replacement or insurance. Adding them would change IRR.
5. FY2025-26 tariffs are used for 25 years with 2 % escalation (ASSUMED). The FY2026-27 order was not found. The season months for Summer/Monsoon/Winter are not defined for industry in the document (only July to October is called monsoon, in an agriculture clause); the three columns differ by 2 paise, so one flat value is used.
6. The load is an assumed factory, not a measured one.
"""
open(os.path.join(HERE, "results.md"), "w", encoding="utf-8").write(text)
print("wrote resco/results.md")
